import { format, parseISO } from 'date-fns';
import { File, Paths } from 'expo-file-system';
import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import { Platform } from 'react-native';
import { outcomeMap } from '@/components/ui/StatusPill';
import type { HearingRow } from '@/services/hearings';

const esc = (s: string | undefined | null) => (s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);

/** "12", "12A", "Hall 3": numbers first, in numeric order. */
const byNumber = (a?: string, b?: string) => {
  const na = parseInt(a ?? '', 10);
  const nb = parseInt(b ?? '', 10);
  if (Number.isNaN(na) !== Number.isNaN(nb)) return Number.isNaN(na) ? 1 : -1;
  return (na || 0) - (nb || 0) || (a ?? '').localeCompare(b ?? '');
};

const caseNo = (h: HearingRow) => {
  const c = h.case;
  const n = c.caseNumber && c.caseYear && !c.caseNumber.includes(String(c.caseYear)) ? `${c.caseNumber}/${c.caseYear}` : c.caseNumber;
  return [c.caseType?.name, n].filter(Boolean).join(' ');
};

/**
 * The day's hearings as a printable page, grouped by court and ordered by court room and item
 * number: everything needed at court without opening the app.
 */
export function todayHearingsHtml(rows: HearingRow[], date: string, advocate?: string) {
  const groups = new Map<string, HearingRow[]>();
  for (const h of rows) {
    const key = h.case.court?.name ?? 'Court not set';
    groups.set(key, [...(groups.get(key) ?? []), h]);
  }
  let serial = 0;
  const sections = [...groups.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([court, list]) => {
      const body = [...list]
        .sort((a, b) => byNumber(a.courtRoom ?? a.case.courtRoom, b.courtRoom ?? b.case.courtRoom) || byNumber(a.itemNumber, b.itemNumber) || (a.time ?? '').localeCompare(b.time ?? ''))
        .map((h) => {
          serial += 1;
          const c = h.case;
          const clients = c.clients.map((cl) => `${esc(cl.fullName)}<br><span class="muted">+91 ${esc(cl.phone)}</span>`).join('<br>');
          return `<tr>
            <td class="num">${serial}</td>
            <td class="num">${esc(h.itemNumber) || '—'}</td>
            <td class="num"><b>${esc(h.courtRoom ?? c.courtRoom) || '—'}</b></td>
            <td><b>${esc(caseNo(h)) || '—'}</b>${c.cnr ? `<br><span class="muted">${esc(c.cnr)}</span>` : ''}</td>
            <td>${esc(c.title)}</td>
            <td>${esc(c.judge) || '—'}</td>
            <td>${esc(h.purpose ?? c.stage) || '—'}${h.time ? `<br><span class="muted">${esc(h.time)}</span>` : ''}${h.lastOutcome ? `<br><span class="muted">Last: ${esc(outcomeMap[h.lastOutcome].label)}</span>` : ''}</td>
            <td>${clients || '—'}</td>
          </tr>`;
        })
        .join('');
      return `<h2>${esc(court)} <span class="count">${list.length} ${list.length === 1 ? 'matter' : 'matters'}</span></h2>
        <table>
          <thead><tr><th>#</th><th>Item</th><th>Room</th><th>Case no.</th><th>Parties</th><th>Judge</th><th>Purpose</th><th>Client</th></tr></thead>
          <tbody>${body}</tbody>
        </table>`;
    })
    .join('');

  const day = format(parseISO(date), 'EEEE, d MMMM yyyy');
  return `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
  <style>
    @page { size: A4 landscape; margin: 12mm; }
    body { font-family: -apple-system, Roboto, 'Segoe UI', Arial, sans-serif; color: #111; font-size: 10.5px; }
    h1 { font-size: 18px; margin: 0; }
    .sub { color: #555; margin: 2px 0 14px; font-size: 11px; }
    h2 { font-size: 13px; margin: 16px 0 6px; padding-bottom: 4px; border-bottom: 2px solid #222; }
    .count { font-weight: normal; color: #666; font-size: 11px; }
    table { width: 100%; border-collapse: collapse; page-break-inside: auto; }
    tr { page-break-inside: avoid; }
    th { text-align: left; background: #f1f1f1; font-size: 9.5px; text-transform: uppercase; letter-spacing: .03em; }
    th, td { border: 1px solid #ccc; padding: 5px 6px; vertical-align: top; }
    td.num { text-align: center; white-space: nowrap; }
    .muted { color: #666; font-size: 9.5px; }
    .foot { margin-top: 14px; color: #888; font-size: 9px; }
  </style></head><body>
  <h1>Hearings · ${esc(day)}</h1>
  <div class="sub">${rows.length} ${rows.length === 1 ? 'hearing' : 'hearings'} in ${groups.size} ${groups.size === 1 ? 'court' : 'courts'}${advocate ? ` · ${esc(advocate)}` : ''}</div>
  ${sections || '<p>No hearings listed.</p>'}
  <div class="foot">Generated by Vakil.app on ${esc(format(new Date(), "d MMM yyyy, h:mm a"))}. Check the court's cause list for final item numbers.</div>
  </body></html>`;
}

/** Makes the PDF and opens the share sheet (save to Files, WhatsApp, print). Web opens the print dialog. */
export async function shareTodayHearingsPdf(rows: HearingRow[], date: string, advocate?: string) {
  const html = todayHearingsHtml(rows, date, advocate);
  if (Platform.OS === 'web') {
    await Print.printAsync({ html });
    return;
  }
  const { uri } = await Print.printToFileAsync({ html, width: 842, height: 595 });
  // A readable file name for WhatsApp / Files: "Hearings 21 Oct 2026.pdf".
  let shareUri = uri;
  try {
    const dest = new File(Paths.cache, `Hearings ${format(parseISO(date), 'd MMM yyyy')}.pdf`);
    if (dest.exists) dest.delete();
    new File(uri).move(dest);
    shareUri = dest.uri;
  } catch {
    /* keep the generated name */
  }
  await Sharing.shareAsync(shareUri, { mimeType: 'application/pdf', UTI: 'com.adobe.pdf', dialogTitle: "Today's hearings" });
}
